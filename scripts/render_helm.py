#!/usr/bin/env python3
"""Render helm/vscode-it.yml, the galaxy-helm values overlay, from tool/.

The overlay embeds the tool XML as a ConfigMap file, so it would drift from
tool/interactivetool_vscode.xml otherwise. Run after any change under tool/:

    scripts/render_helm.py [--mode path|domain] [--no-tool] [--output FILE]

Macros are expanded here (galaxy-helm's extraFileMappings is one file per entry,
and keeping macros.xml beside the tool only to resolve three tokens is not worth
a second mapping). The result is the overlay galaxy-k8s-boot ships as
mixins/vscode-it.yml.
"""
import argparse
import pathlib
import re
import textwrap

ROOT = pathlib.Path(__file__).resolve().parents[1]
TOOL = ROOT / "tool/interactivetool_vscode.xml"
MACROS = ROOT / "tool/macros.xml"
OUT = ROOT / "helm/vscode-it.yml"


def expand(mode: str) -> str:
    macros = MACROS.read_text()
    tokens = dict(re.findall(r'<token name="(@[A-Z_]+@)">([^<]*)</token>', macros))
    tokens["@REQUIRES_DOMAIN@"] = "True" if mode == "domain" else "False"
    xml = TOOL.read_text()
    # Inline the single macro the tool expands and drop the import.
    xml = re.sub(r"\n    <macros>\n        <import>macros.xml</import>\n    </macros>", "", xml)
    xml = xml.replace(
        '    <expand macro="requirements"/>',
        "    <requirements>\n        <container type=\"docker\">@CONTAINER@</container>\n    </requirements>",
    )
    # The overlay is a single text file and cannot carry the icon image.
    xml, dropped = re.subn(r"\n    <!--[^>]*?-->\n    <icon [^>]*/>", "", xml)
    assert dropped == 1, "icon element not found"
    # Comments that only make sense beside macros.xml, before the tokens go.
    xml = xml.replace("see @REQUIRES_DOMAIN@ in macros.xml", "see scripts/render_helm.py --mode")
    xml = xml.replace("(see config/tpv_rules.yml)", "(the TPV rule below)")
    for name, value in tokens.items():
        xml = xml.replace(name, value)
    return xml.rstrip() + "\n"


HEADER = """\
# VS Code as a Galaxy Interactive Tool (OpenVSCode Server), galaxy-helm overlay.
#
# GENERATED by scripts/render_helm.py from tool/interactivetool_vscode.xml; edit
# there and re-render. Mode: {mode}.
#
# Path-based means every IT is served under Galaxy's own host and prefix:
#   https://<galaxy host><prefix>/interactivetool/ep/<id>/<token>/
# so it needs no per-IT hostname, wildcard DNS or wildcard certificate. That is the
# only layout that can work behind Leonardo on Terra, where Galaxy lives at a long
# path under a shared proxy host and nothing can hang a subdomain off it.
# Domain-based gives every session a subdomain of interactivetools_proxy_host and
# needs a wildcard DNS record and certificate (k8s_interactivetools_tls_secret).
#
# Galaxy's KubernetesJobRunner creates one Ingress per running IT. ingress-nginx
# matches the longest path first, so in path mode the IT Ingress wins over Galaxy's
# own prefix Ingress and the request is forwarded to the IT pod with the FULL path.
# Nothing strips the prefix, which is why this uses OpenVSCode Server
# (--server-base-path) rather than code-server, which can only live at a stripped
# subpath and answers 400/404 otherwise.
#
# Use with galaxy-helm:  helm install ... -f values.yml -f vscode-it.yml
# galaxy-k8s-boot ships this file as mixins/vscode-it.yml and appends it by default.
#
# NOTE: `{{{{ }}}}` below is HELM templating (rendered by the chart's `tpl`).

configs:
  galaxy.yml:
    galaxy:
      interactivetools_enable: true
      # Path mode: EMPTY on purpose. The runner builds every IT Ingress with
      # `host: <interactivetools_proxy_host>`; the chart defaults it to the ingress
      # host, which a host-less deployment leaves unset, so it renders as "localhost"
      # and the IT Ingress never matches a real request. An empty host matches every
      # host, like Galaxy's own Ingress, and makes Galaxy hand the browser a RELATIVE
      # IT URL, which is what a proxied deployment (Leonardo) needs. When Galaxy's
      # Ingress names a host, set this to that host (ingress-nginx routes by Host
      # before path). Domain mode: the host the per-session subdomains hang off.
      interactivetools_proxy_host: ""
      # interactivetools_base_path is left to the chart: it tracks the ingress path.
      #
      # The chart default is a RELATIVE path, which Galaxy resolves against the
      # pod-local server root rather than the shared data dir. The web and job
      # handlers then keep separate map files and stopping an IT fails with
      # "no such table: gxitproxy". Pin it to the shared volume.
      interactivetools_map: /galaxy/server/database/interactivetools_map.sqlite
{tool_config}  job_conf.yml:
    runners:
      k8s:
        # Path mode: no per-IT TLS block, ingress-nginx already serves 443 for every
        # host with the controller's default certificate. With the chart default
        # (true) and no TLS secret the runner would emit a tls entry with an empty
        # host and an empty secret name. Domain mode: set true and name the wildcard
        # certificate's Secret in k8s_interactivetools_tls_secret.
        k8s_interactivetools_use_ssl: false
        # The chart copies Galaxy's ingress annotations onto every IT Ingress,
        # including cert-manager's cluster-issuer. Replace them with the long
        # timeouts a WebSocket-heavy IDE needs.
        k8s_interactivetools_ingress_annotations: |
          nginx.ingress.kubernetes.io/proxy-read-timeout: "3600"
          nginx.ingress.kubernetes.io/proxy-send-timeout: "3600"
          nginx.ingress.kubernetes.io/proxy-body-size: "1G"

jobs:
  rules:
    tpv_rules_local.yml:
      tools:
        # Pin every interactive tool to the k8s destination: it is the only one that
        # can create the Service + Ingress an IT needs. Tag that destination
        # `interactive` in its accept list; batch/cloud destinations must not carry it.
        # TPV matches from the START of the tool id, and a ToolShed-installed tool's
        # id starts with the ToolShed host, hence the leading `.*`.
        .*interactive_tool_.*:
          params:
            # What $__galaxy_url__ (GALAXY_URL in the tool) resolves to for IT jobs:
            # Galaxy's own nginx Service, reached from inside the cluster. The public
            # URL is wrong here. On a plain VM it is unset, and on Terra it points at
            # the Leonardo proxy, which only admits browser sessions.
            galaxy_infrastructure_url: 'http://{{{{ include "galaxy.fullname" . }}}}-nginx:{{{{ .Values.service.port }}}}{{{{ .Values.ingress.path }}}}'
          scheduling:
            require:
              - interactive
{embedded}"""

# The two parts that put the tool itself on the server. Left out with --no-tool,
# for a Galaxy that gets the tool from a ToolShed and needs only the configuration.
TOOL_CONFIG = """\
      # Chart default (verbatim, so the standard + shed confs are preserved -- the chart
      # tpl-renders this, hence the {{if}}) + the interactive tool conf added below.
      tool_config_file: "/galaxy/server/config/tool_conf.xml{{if .Values.setupJob.downloadToolConfs.enabled}},{{ .Values.setupJob.downloadToolConfs.volume.mountPath }}/config/shed_tool_conf.xml{{end}},/galaxy/server/config/interactive_tool_conf.xml"
"""

EMBEDDED = """
extraFileMappings:
  # The tool definition. Placed in Galaxy's tool_path (/galaxy/server/database/tools)
  # beside the bundled ITs, so the tool_conf below resolves it as interactive/vscode.xml.
  /galaxy/server/database/tools/interactive/vscode.xml:
    applyToJob: true       # the handler that dispatches the IT pod loads the toolbox
    applyToWeb: true       # the web handler renders/serves the tool panel
    applyToWorkflow: true  # keep every toolbox-loading pod consistent
    applyToNginx: false
    applyToSetupJob: false
    useSecret: false
    tpl: false
    content: |
{xml}
  # Adds the tool to the toolbox. Referenced by tool_config_file above.
  /galaxy/server/config/interactive_tool_conf.xml:
    applyToJob: true
    applyToWeb: true
    applyToWorkflow: true
    applyToNginx: false
    applyToSetupJob: false
    useSecret: false
    tpl: false
    content: |
      <?xml version="1.0"?>
      <toolbox monitor="true">
        <section id="interactive_custom" name="Interactive Tools">
          <tool file="interactive/vscode.xml" />
        </section>
      </toolbox>
"""


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--mode", choices=("path", "domain"), default="path")
    ap.add_argument("--output", type=pathlib.Path, default=OUT)
    ap.add_argument("--no-tool", action="store_true",
                    help="configuration only: leave out the embedded tool XML and its tool conf, "
                         "for a Galaxy that installs the tool from a ToolShed")
    args = ap.parse_args()
    if args.no_tool:
        tool_config = embedded = ""
    else:
        tool_config = TOOL_CONFIG
        embedded = EMBEDDED.replace("{xml}", textwrap.indent(expand(args.mode), "      "))
    args.output.write_text(HEADER.format(mode=args.mode, tool_config=tool_config, embedded=embedded))
    print(f"wrote {args.output} ({args.mode} mode{', no embedded tool' if args.no_tool else ''})")


if __name__ == "__main__":
    main()
